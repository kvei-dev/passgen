// Builds src/wordlist.js from data/eff_large_wordlist.txt (EFF large wordlist).
// Only purely alphabetic words are kept (drops "drop-down", "t-shirt", ...).
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../data/eff_large_wordlist.txt', import.meta.url);
const out = new URL('../src/wordlist.js', import.meta.url);

const words = readFileSync(src, 'utf8')
  .split('\n')
  .map((l) => l.trim().split(/\s+/)[1])
  .filter((w) => w && /^[a-z]+$/.test(w));

if (new Set(words).size !== words.length) throw new Error('duplicate words');

const js = `// GENERATED by tools/build-wordlist.mjs - do not edit.
// Source: EFF large wordlist (https://www.eff.org/deeplinks/2016/07/new-wordlists-random-passphrases),
// (c) Electronic Frontier Foundation, licensed CC BY 3.0 US.
// Hyphenated entries were removed, ${words.length} words remain.
export const WORDS = '${words.join(' ')}'.split(' ');
`;
writeFileSync(out, js);
console.log(`wrote ${words.length} words`);
