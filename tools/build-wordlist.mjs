// Builds src/wordlist.js from the files in data/.
//
//   common = EFF large list  U  SCOWL levels 10+20 (base forms)
//   large  = common          U  SCOWL level 35      (base forms)
//
// Filters: lowercase a-z only, 4-9 letters for SCOWL words (EFF words keep their
// own 3-9 range), no blocklisted words, no derived forms (plurals, -ed, -ing,
// -ly, -er/-est) whose stem is in the same list.
import { readFileSync, writeFileSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../data/${p}`, import.meta.url), 'utf8');
const lines = (t) => t.split('\n').map((s) => s.trim().toLowerCase()).filter((s) => s && !s.startsWith('#'));

const blocked = new Set([...lines(read('blocklist-ldnoobw.txt')), ...lines(read('blocklist-extra.txt'))]);
// Substrings that are never acceptable anywhere inside a word.
const BAD_SUBSTRINGS = ['nigg', 'fuck', 'shit', 'cunt', 'whore', 'slut', 'porn', 'bitch', 'pedo', 'rapist'];
const isBad = (w) => blocked.has(w) || BAD_SUBSTRINGS.some((s) => w.includes(s));

const eff = lines(read('eff_large_wordlist.txt'))
  .map((l) => l.split(/\s+/)[1])
  .filter((w) => w && /^[a-z]+$/.test(w) && !isBad(w));

const scowl = (levels) => {
  const set = new Set();
  for (const l of levels) for (const w of JSON.parse(read(`scowl-english-words-${l}.json`))) set.add(w);
  return set;
};

function isDerived(w, set) {
  const stems = [];
  const e = (s) => w.endsWith(s);
  if (e('ies')) stems.push(w.slice(0, -3) + 'y');
  if (e('es')) stems.push(w.slice(0, -2));
  if (e('s') && !e('ss')) stems.push(w.slice(0, -1));
  if (e('ied')) stems.push(w.slice(0, -3) + 'y');
  if (e('ed')) {
    stems.push(w.slice(0, -2), w.slice(0, -1));
    if (w[w.length - 3] === w[w.length - 4]) stems.push(w.slice(0, -3));
  }
  if (e('ing')) {
    stems.push(w.slice(0, -3), w.slice(0, -3) + 'e');
    if (w[w.length - 4] === w[w.length - 5]) stems.push(w.slice(0, -4));
  }
  if (e('ly')) stems.push(w.slice(0, -2), w.slice(0, -2) + 'le');
  if (e('ily')) stems.push(w.slice(0, -3) + 'y');
  if (e('er')) stems.push(w.slice(0, -2), w.slice(0, -1));
  if (e('est')) stems.push(w.slice(0, -3), w.slice(0, -2));
  if (e('ier')) stems.push(w.slice(0, -3) + 'y');
  if (e('iest')) stems.push(w.slice(0, -4) + 'y');
  return stems.some((s) => set.has(s));
}

const baseForms = (set) =>
  [...set].filter((w) => /^[a-z]{4,9}$/.test(w) && !isBad(w) && !isDerived(w, set));

const s20 = scowl(['10', '20']);
const s35 = scowl(['10', '20', '35']);

const common = [...new Set([...eff, ...baseForms(s20)])].sort();
const commonSet = new Set(common);
const extra = [...new Set(baseForms(s35))].filter((w) => !commonSet.has(w)).sort();

for (const w of [...common, ...extra]) if (!/^[a-z]{3,9}$/.test(w) || isBad(w)) throw new Error(`bad word: ${w}`);

const js = `// GENERATED by tools/build-wordlist.mjs - do not edit. Sources: data/NOTICE.md
// EFF large wordlist (c) EFF, CC BY 3.0 US; SCOWL (c) Kevin Atkinson, see data/SCOWL-Copyright.txt.
// common: ${common.length} words, large: ${common.length + extra.length} words.
const COMMON = '${common.join(' ')}';
const EXTRA = '${extra.join(' ')}';
export const WORD_LISTS = {
  common: COMMON.split(' '),
  large: (COMMON + ' ' + EXTRA).split(' '),
};
`;
writeFileSync(new URL('../src/wordlist.js', import.meta.url), js);
console.log(`common=${common.length} large=${common.length + extra.length}`);
